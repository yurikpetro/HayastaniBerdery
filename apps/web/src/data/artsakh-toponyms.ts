function transliterateHy(text: string, table: Record<string, string>) {
  return text
    .toLocaleLowerCase('hy')
    .split('')
    .map((char) => table[char] ?? char)
    .join('')
    .replace(/\s+/g, ' ')
    .trim()
}

function titleCase(text: string) {
  return text
    .split(' ')
    .map((part) => (part ? `${part[0].toLocaleUpperCase()}${part.slice(1)}` : part))
    .join(' ')
}

function toponym(hy: string, ru?: string, en?: string): LocalizedText {
  return {
    hy,
    ru: ru ?? titleCase(transliterateHy(hy, hyToRu)),
    en: en ?? titleCase(transliterateHy(hy, hyToEn)),
  }
}

